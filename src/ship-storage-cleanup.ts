import {constants, type Stats} from 'node:fs';
import {lstat, mkdir, open, opendir, realpath, rename, rmdir, writeFile} from 'node:fs/promises';
import {createHash, randomUUID} from 'node:crypto';
import {execFile} from 'node:child_process';
import {homedir} from 'node:os';
import * as path from 'node:path';

const LOCK = '.package-cache-lock', MAX_BYTES = 512 * 1024 * 1024;
interface Pin {readonly directory: 'codeoss-package' | 'pills'; readonly name: string; readonly sha256: string}
interface Fingerprint {readonly dev: number; readonly ino: number; readonly size: number; readonly mtimeMs: number; readonly ctimeMs: number; readonly sha256: string}
export interface CleanupItem {readonly id: string; readonly file: string; readonly allocatedBytes: number | null; readonly logicalBytes: number; readonly sha256: string}
export interface CleanupPreview {readonly items: readonly CleanupItem[]; readonly notes: readonly string[]}
interface Held {item: CleanupItem; fingerprint: Fingerprint; pin: Pin}
export interface CleanupEnvironment {
  readonly home: string; readonly uid: number; readonly platform: string;
  readonly idle: (files: readonly string[], root: string) => Promise<void>;
}
function refuse(message: string): never {throw new Error(message);}
function same(a: Fingerprint, b: Fingerprint): boolean {return Object.keys(a).every(k => a[k as keyof Fingerprint] === b[k as keyof Fingerprint]);}
function fingerprint(s: Stats, sha256: string): Fingerprint {return {dev: s.dev, ino: s.ino, size: s.size, mtimeMs: s.mtimeMs, ctimeMs: s.ctimeMs, sha256};}
const hash = (v: unknown): v is string => typeof v === 'string' && /^[a-f0-9]{64}$/.test(v);
/** This is generated by package.sh from its existing pins and signed inside the app. */
export function cleanupPins(value: unknown): readonly Pin[] {
  if (!value || typeof value !== 'object') refuse('This package has no supported download inventory.');
  const r = value as Record<string, unknown>, editor = r.editor as Record<string, unknown>, pill = r.pill as Record<string, unknown>;
  if (r.schema !== 'readymade-cache-downloads-v1' || Object.keys(r).length !== 3 || !editor || !pill ||
      Object.keys(editor).length !== 2 || Object.keys(pill).length !== 2 || typeof editor.name !== 'string' ||
      !/^VSCodium-darwin-arm64-[0-9]{1,4}\.[0-9]{1,4}\.[0-9]{1,8}\.zip$/.test(editor.name) || !hash(editor.sha256) ||
      !hash(pill.sha256) || pill.name !== pill.sha256 + '.pill') refuse('This package has no supported download inventory.');
  return Object.freeze([{directory: 'codeoss-package', name: editor.name, sha256: editor.sha256},
    {directory: 'pills', name: pill.name as string, sha256: pill.sha256}].map(p => Object.freeze(p as Pin)));
}
async function smallJSON(file: string): Promise<unknown> {
  if (await realpath(file) !== file) refuse('Linked package metadata is not accepted.');
  const fd = await open(file, constants.O_RDONLY | constants.O_NOFOLLOW);
  try {const s = await fd.stat(); if (!s.isFile() || s.nlink !== 1 || s.size > 4096) refuse('Download metadata is unavailable.');
    const bytes = Buffer.alloc(4097); const {bytesRead} = await fd.read(bytes, 0, bytes.length, 0);
    if (bytesRead !== s.size) refuse('Download metadata changed.'); return JSON.parse(bytes.subarray(0, bytesRead).toString());
  } finally {await fd.close();}
}
function command(file: string, args: string[], absence = false): Promise<string> {
  return new Promise((resolve, reject) => execFile(file, args, {encoding: 'utf8', timeout: 3000, maxBuffer: 1024 * 1024}, (error, stdout, stderr) => {
    if (!stderr && (!error || absence && error.code === 1 && !stdout)) resolve(stdout);
    else reject(new Error('Active work could not be ruled out. No download was moved.'));
  }));
}
/** Running cached runtimes are protected, but do not consume the ZIP/pill downloads.
 * Empty or malformed process observations cannot establish an idle builder. */
export function cleanupProcessesClear(processes: string, root: string): boolean {
  const rows = processes.split('\n').filter(row => row.trim());
  const downloads = ['codeoss-package', 'pills'].map(name => path.join(root, name) + '/');
  return rows.length > 0 && rows.every(row => /^\s*\d+\s+\d+\s+\S/.test(row) &&
    !/(?:^|[\s/'"])package\.sh(?:[\s'"]|$)/.test(row) && !downloads.some(p => row.includes(p)));
}
/** Inspect process metadata only; never signal a builder or read its files. */
export async function cleanupIdle(files: readonly string[], root: string): Promise<void> {
  if (process.platform !== 'darwin') refuse('Download cleanup is available only on this Mac.');
  const processes = await command('/bin/ps', ['-axo', 'pid=,uid=,args=']);
  if (!cleanupProcessesClear(processes, root))
    refuse('A builder or cache user may be active. Finish that work before cleanup.');
  const present: string[] = [];
  for (const file of files) try {await lstat(file); present.push(file);} catch (error) {if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;}
  if (present.length && (await command('/usr/sbin/lsof', ['-nP', '-Fpn', '--', ...present], true)).trim())
    refuse('A download is open in another process. Finish that work before cleanup.');
}

/** A bounded local maintenance adapter. No recursive deletion, cleanup timer or ship operation. */
export class DownloadCleanup {
  private readonly root: string;
  private readonly held = new Map<string, Held>();
  private busy = false;
  constructor(private readonly extensionPath: string, private readonly env: CleanupEnvironment = {
    home: homedir(), uid: process.getuid?.() ?? -1, platform: process.platform, idle: cleanupIdle,
  }) {this.root = path.join(env.home, '.cache/readymade');}
  private async directory(file: string, privateMode = false): Promise<Stats> {
    const s = await lstat(file);
    if (!s.isDirectory() || s.isSymbolicLink() || s.uid !== this.env.uid || (s.mode & 0o022) ||
        privateMode && (s.mode & 0o777) !== 0o700 || await realpath(file) !== file) refuse('Cleanup requires owned, unlinked directories.');
    return s;
  }
  private async parents(pin?: Pin): Promise<void> {
    if (this.env.platform !== 'darwin' || !path.isAbsolute(this.env.home) || path.resolve(this.env.home) !== this.env.home || this.env.uid < 0)
      refuse('Download cleanup is unavailable on this host.');
    for (const dir of [this.env.home, path.join(this.env.home, '.cache'), this.root]) await this.directory(dir);
    if (pin) await this.directory(path.join(this.root, pin.directory), true);
  }
  private async unlocked(): Promise<void> {
    try {await lstat(path.join(this.root, LOCK));} catch (error) {if ((error as NodeJS.ErrnoException).code === 'ENOENT') return; throw error;}
    refuse('Packaging or cleanup owns the cache lock. Retained locks are never removed here.');
  }
  private async unfinished(pin: Pin): Promise<void> {
    const dir = await opendir(path.join(this.root, pin.directory)); let count = 0;
    for await (const entry of dir) {
      if (++count > 32) refuse('Cache directory exceeds the inspection limit. Nothing was moved.');
      if (entry.name.endsWith('.partial') || entry.name.startsWith('.download.')) refuse('An unfinished download is retained. Finish or inspect it before cleanup.');
    }
  }
  private async inspect(pin: Pin): Promise<{fingerprint: Fingerprint; allocated: number | null}> {
    await this.parents(pin); await this.unfinished(pin);
    const file = path.join(this.root, pin.directory, pin.name), before = await lstat(file);
    if (!before.isFile() || before.isSymbolicLink() || before.uid !== this.env.uid || before.nlink !== 1 || (before.mode & 0o777) !== 0o600 ||
        !Number.isSafeInteger(before.size) || before.size < 1 || before.size > MAX_BYTES) refuse('Download is not an eligible private regular file.');
    const fd = await open(file, constants.O_RDONLY | constants.O_NOFOLLOW), deadline = performance.now() + 15000;
    try {
      if (!same(fingerprint(before, ''), fingerprint(await fd.stat(), ''))) refuse('Download changed before inspection.');
      const h = createHash('sha256'), bytes = Buffer.alloc(256 * 1024); let offset = 0;
      while (offset < before.size) {
        if (performance.now() >= deadline) refuse('Download verification reached its time limit.');
        const read = await fd.read(bytes, 0, Math.min(bytes.length, before.size - offset), offset);
        if (!read.bytesRead) refuse('Download changed during inspection.');
        h.update(bytes.subarray(0, read.bytesRead)); offset += read.bytesRead;
      }
      const sha = h.digest('hex');
      if (sha !== pin.sha256 || !same(fingerprint(before, ''), fingerprint(await fd.stat(), '')) ||
          !same(fingerprint(before, ''), fingerprint(await lstat(file), ''))) refuse('Download does not match its pinned contents. Preserve it for inspection.');
      return {fingerprint: fingerprint(before, sha), allocated: Number.isSafeInteger(before.blocks * 512) ? before.blocks * 512 : null};
    } finally {await fd.close();}
  }
  async preview(): Promise<CleanupPreview> {
    if (this.busy) refuse('A download maintenance action is already in progress.');
    this.busy = true; this.held.clear();
    try {
      await this.parents(); await this.unlocked();
      const pins = cleanupPins(await smallJSON(path.join(this.extensionPath, 'backend/runtime/cache-downloads.json')));
      const files = pins.map(p => path.join(this.root, p.directory, p.name)); await this.env.idle(files, this.root);
      const items: CleanupItem[] = [], notes: string[] = [];
      for (const pin of pins) try {
        const seen = await this.inspect(pin), item: CleanupItem = Object.freeze({id: randomUUID(), file: path.join(this.root, pin.directory, pin.name),
          allocatedBytes: seen.allocated, logicalBytes: seen.fingerprint.size, sha256: pin.sha256});
        items.push(item); this.held.set(item.id, {item, fingerprint: seen.fingerprint, pin});
      } catch (error) {notes.push(pin.name + ': ' + ((error as NodeJS.ErrnoException).code === 'ENOENT' ? 'Not cached.' : error instanceof Error ? error.message : 'Not eligible.'));}
      await this.unlocked(); await this.env.idle(files, this.root);
      return Object.freeze({items: Object.freeze(items), notes: Object.freeze(notes)});
    } catch (error) {this.held.clear(); throw error;} finally {this.busy = false;}
  }
  async trash(id: string, confirm: (item: CleanupItem) => Promise<boolean>): Promise<string | undefined> {
    if (this.busy) refuse('A download maintenance action is already in progress.');
    const held = this.held.get(id); if (!held) refuse('Preview this exact download again before moving it.');
    this.held.delete(id); this.busy = true;
    let lock: Stats | undefined;
    try {
      if (!await confirm(held.item)) return;
      await this.parents(held.pin);
      const lockPath = path.join(this.root, LOCK);
      await mkdir(lockPath, {mode: 0o700}); lock = await this.directory(lockPath, true);
      await this.env.idle([held.item.file], this.root);
      const fresh = await this.inspect(held.pin);
      if (!same(fresh.fingerprint, held.fingerprint)) refuse('The previewed file changed. Nothing was moved.');
      const trashRoot = path.join(this.env.home, '.Trash');
      // Never create or substitute the operating system's Trash directory.
      const trash = await this.directory(trashRoot, true);
      if (trash.dev !== fresh.fingerprint.dev) refuse('Trash is on another volume. Nothing was moved.');
      await this.env.idle([held.item.file], this.root); await this.parents(held.pin);
      const currentLock = await this.directory(lockPath, true);
      if (currentLock.dev !== lock.dev || currentLock.ino !== lock.ino) refuse('The maintenance lock changed. Nothing was moved.');
      if (!same(fingerprint(await lstat(held.item.file), held.pin.sha256), held.fingerprint)) refuse('The previewed file changed. Nothing was moved.');
      const folder = path.join(trashRoot, 'Readymade-' + randomUUID()); await mkdir(folder, {mode: 0o700}); await this.directory(folder, true);
      const destination = path.join(folder, held.pin.name);
      // The receipt survives even if the rename has an unknown outcome. Never retry it automatically.
      await writeFile(path.join(folder, 'restore.json'), JSON.stringify({schema: 'readymade-download-trash-v1', original: held.item.file,
        destination, sha256: held.pin.sha256, bytes: held.item.logicalBytes, created: new Date().toISOString(),
        restore: 'Move the download back to its original path only if that path is empty. Never overwrite a new download.'}) + '\n', {flag: 'wx', mode: 0o600});
      try {await rename(held.item.file, destination);}
      catch {refuse(`Move outcome is uncertain. Inspect ${folder}; nothing was retried.`);}
      const moved = await lstat(destination);
      if (moved.dev !== held.fingerprint.dev || moved.ino !== held.fingerprint.ino || moved.size !== held.fingerprint.size)
        refuse('Move outcome is uncertain. Inspect the retained Trash folder; nothing was retried.');
      return folder;
    } finally {
      try {
        if (lock) {
          const file = path.join(this.root, LOCK), current = await lstat(file).catch(() => undefined);
          if (current?.dev === lock.dev && current.ino === lock.ino && current.isDirectory() && !current.isSymbolicLink()) await rmdir(file);
        }
      } finally {this.busy = false;}
    }
  }
}
